"""Builds docs/FUNCTION_MAP.md from the "// @ 0x......" annotations in src/.

Every original function of the game code range (0x401000 - 0x41c550) found in
reference/disasm/sumofull_game.asm is listed with the symbol and location of
its reconstruction, or flagged as not (yet) annotated.

usage: python tools/gen_function_map.py
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
GAME_START, GAME_END = 0x401000, 0x41C550

ITEM = r"0x[0-9a-fA-F]+(?:\s*\([^)]*\))?"
# "// @ 0x1234", "// @ 0x1234 (note), 0x5678 / 0x9abc", continued on "//   0x..." lines
ADDR = re.compile(r"//\s*@\s*(" + ITEM + r"(?:\s*[,/]\s*" + ITEM + r")*)")
CONT = re.compile(r"^\s*//\s+(" + ITEM + r"(?:\s*[,/]\s*" + ITEM + r")*)")
HEX = re.compile(r"0x([0-9a-fA-F]+)")
# a C++ declaration/definition: capture the name before the parameter list
DECL = re.compile(r"([A-Za-z_][\w:~]*(?:\s*operator\s*[^\s(]+)?)\s*\(")
DATA = re.compile(r"([A-Za-z_]\w*)\s*(?:\[[^\]]*\])*\s*(?:=|;)")


def symbol_for(lines, i, comment_col):
    """Name annotated by the comment on line i (same line, else following lines)."""
    code = lines[i][:comment_col].strip()
    candidates = [code] if code else []
    if not code:
        for j in range(i + 1, min(i + 8, len(lines))):
            t = lines[j].strip()
            if t and not t.startswith("//"):
                candidates.append(t)
                break
    for c in candidates:
        m = DECL.search(c)
        if m and not c.startswith(("if", "for", "while", "return")):
            return m.group(1).split("::")[-1] if "operator" not in m.group(1) else m.group(1)
        m = DATA.search(c)
        if m:
            return m.group(1)
    return None


def main():
    found = {}
    for base, _, files in os.walk(os.path.join(ROOT, "src")):
        for name in sorted(files):
            if not name.endswith((".cpp", ".h", ".inc")) or "generated" in base:
                continue
            path = os.path.join(base, name)
            rel = os.path.relpath(path, ROOT).replace("\\", "/")
            lines = open(path, encoding="utf-8", errors="replace").read().splitlines()
            for i, line in enumerate(lines):
                m = ADDR.search(line)
                if not m:
                    continue
                sym = symbol_for(lines, i, m.start())
                text = m.group(1)
                j = i + 1
                while j < len(lines) and CONT.match(lines[j]):
                    text += " " + CONT.match(lines[j]).group(1)
                    j += 1
                for h in HEX.findall(re.sub(r"\([^)]*\)", "", text)):
                    a = int(h, 16)
                    entry = (sym or "?", "%s:%d" % (rel, i + 1))
                    # prefer definitions (.cpp) over declarations (.h)
                    if a not in found or (rel.endswith(".cpp") and ".h:" in found[a][1]):
                        found[a] = entry

    asm = open(os.path.join(ROOT, "reference", "disasm", "sumofull_game.asm"), encoding="utf-8", errors="replace").read()
    funcs = sorted({int(h, 16) for h in re.findall(r"^; ==== FUN_([0-9a-fA-F]+) @", asm, re.M)})
    funcs = [f for f in funcs if GAME_START <= f < GAME_END]

    out = ["# Function map", "",
           "Original address -> reconstruction, generated by `tools/gen_function_map.py`",
           "from the `// @ 0x......` annotations (do not edit by hand).", "",
           "Game code is 0x401000-0x41c550 of sumofull.exe; sumoeditor.exe has the same",
           "layout (the only difference is the editor flag, see `core/common.h`).", ""]
    mapped = [f for f in funcs if f in found]
    out.append("%d of %d functions in the game range are annotated." % (len(mapped), len(funcs)))
    out.append("")
    out.append("| Address | Symbol | Location |")
    out.append("|---|---|---|")
    for f in funcs:
        if f in found:
            sym, loc = found[f]
            out.append("| `0x%06x` | `%s` | %s |" % (f, sym, loc))
        else:
            out.append("| `0x%06x` | - | *not annotated* |" % f)
    extra = sorted(a for a in found if a not in funcs)
    if extra:
        out += ["", "## Other annotated addresses", "",
                "Data, CRT routines and addresses inside functions referenced by comments.", "",
                "| Address | Symbol | Location |", "|---|---|---|"]
        for a in extra:
            sym, loc = found[a]
            out.append("| `0x%06x` | `%s` | %s |" % (a, sym, loc))
    path = os.path.join(ROOT, "docs", "FUNCTION_MAP.md")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("%s: %d/%d game functions annotated, %d other addresses" % (path, len(mapped), len(funcs), len(extra)))
    missing = [f for f in funcs if f not in found]
    if "-v" in sys.argv:
        for f in missing:
            print("missing 0x%06x" % f)
    return 0


if __name__ == "__main__":
    sys.exit(main())
